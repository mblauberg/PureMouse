import Foundation
import Testing
@testable import PureMouseKit

/// Decodes `config.example.json` and every input in `ConfigGoldenCorpus` and compares a dump of the
/// result (or the failure message) with the committed `ConfigGoldenExpected`. Captured from the
/// decoder before it was restructured to decode on a base, so a refactor that changes any decoded
/// value, error wording or warning order fails here. To change the expectation on purpose, run
/// with `PUREMOUSE_UPDATE_GOLDEN=1` and review the diff.
@Suite struct ConfigGoldenTests {
    static let testsDirectory = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
    static let goldenURL = testsDirectory.appending(path: "ConfigGoldenExpected.swift")
    static let repositoryRoot = testsDirectory.appending(path: "../..").standardized

    /// Every stored field of `value` as indented `label: value` lines, depth first, with
    /// dictionaries and sets in sorted order.
    static func dump(_ value: Any, label: String, indent: Int = 0) -> [String] {
        let pad = String(repeating: "  ", count: indent)
        let mirror = Mirror(reflecting: value)
        func nested(_ header: String, _ children: [(String, Any)]) -> [String] {
            ["\(pad)\(label): \(header)"] + children.flatMap { dump($0.1, label: $0.0, indent: indent + 1) }
        }
        switch mirror.displayStyle {
        case .optional:
            guard let child = mirror.children.first else { return ["\(pad)\(label): nil"] }
            return dump(child.value, label: label, indent: indent)
        case .dictionary:
            let entries: [(String, Any)] = mirror.children.map { child in
                let pair = Array(Mirror(reflecting: child.value).children)
                return (String(describing: pair[0].value), pair[1].value)
            }
            return nested("[\(entries.count)]", entries.sorted { $0.0 < $1.0 })
        case .set:
            let members = mirror.children.map { String(describing: $0.value) }.sorted()
            return ["\(pad)\(label): {\(members.joined(separator: ", "))}"]
        case .collection:
            return nested("[\(mirror.children.count)]", mirror.children.map { ("-", $0.value) })
        case .struct, .class, .enum, .tuple:
            if mirror.children.isEmpty { return ["\(pad)\(label): \(value)"] }
            let name = mirror.displayStyle == .enum ? "\(value)".prefix { $0 != "(" } : "\(mirror.subjectType)".prefix { $0 != "<" }
            return nested(String(name), mirror.children.map { ($0.label ?? "_", $0.value) })
        default:
            return ["\(pad)\(label): \(value)"]
        }
    }

    static func entry(name: String, data: Data) -> String {
        var out = "### \(name)\n"
        do {
            let config = try JSONDecoder().decode(Config.self, from: data)
            out += dump(config, label: "config").joined(separator: "\n") + "\n"
        } catch {
            out += "error: \(ConfigCheck.message(for: error))\n"
        }
        // The validator the menu uses must agree with the decoder.
        do {
            try ConfigCheck.validate(data)
        } catch {
            out += "validate: \(ConfigCheck.message(for: error))\n"
        }
        return out
    }

    static func current() throws -> String {
        var inputs = [(name: "config.example.json",
                       json: try String(contentsOf: repositoryRoot.appending(path: "config.example.json"), encoding: .utf8))]
        inputs += ConfigGoldenCorpus.inputs
        return inputs.map { entry(name: $0.name, data: Data($0.json.utf8)) }.joined(separator: "\n")
    }

    /// The expectation as the Swift source of `ConfigGoldenExpected.swift`.
    static func source(of text: String) -> String {
        let quotes = String(repeating: "\"", count: 3)
        return "// Generated by ConfigGoldenTests with PUREMOUSE_UPDATE_GOLDEN=1; review the diff, do not edit.\n"
            + "enum ConfigGoldenExpected {\n    static let text = #\(quotes)\n\(text)\n\(quotes)#\n}\n"
    }

    @Test func decodedValuesAndMessagesMatchTheGolden() throws {
        let actual = try Self.current()
        if ProcessInfo.processInfo.environment["PUREMOUSE_UPDATE_GOLDEN"] == "1" {
            try Self.source(of: actual).write(to: Self.goldenURL, atomically: true, encoding: .utf8)
            return
        }
        let expected = ConfigGoldenExpected.text
        if actual != expected {
            // Name the first differing entry rather than dumping both texts.
            let a = actual.components(separatedBy: "\n### "), e = expected.components(separatedBy: "\n### ")
            let changed = zip(a, e).first { $0 != $1 }?.0.prefix(while: { $0 != "\n" }) ?? "entry count"
            Issue.record("decoded output differs from ConfigGoldenExpected, first at: \(changed)")
        }
        #expect(actual == expected)
    }

    @Test func corpusCoversSuccessesFailuresAndWarnings() {
        let text = ConfigGoldenExpected.text
        #expect(text.components(separatedBy: "### ").count > 80)
        #expect(text.contains("error: dpi: expected a whole number"))
        #expect(text.contains("is not a per-app setting; ignored"))
        #expect(text.contains("unknownButtons:"))
    }
}
