#!/usr/bin/env python3 -I
"""Writes the device art's typed Swift data (hit cells and part outlines per family) from
regions.json, which export.py writes.

usage: swift_geometry.py <regions.json> <DeviceArtGeometry.swift>"""
import json, sys

CASES = {"mx": "mx", "mx4": "mx4", "compact-anywhere": "compactAnywhere", "compact-m750": "compactM750"}
HEADER = """// Hit cells and part outlines of the device drawings, in art units (the 100 x 124 page of each PDF:
// origin top-left, y down, front of the mouse up). Data only: which control a part binds is
// `DeviceArt.models`, and the drawings are `assets/silhouettes` (docs/adr/0013-silhouettes.md).
// A cell is where a pointer hits; the outline is the part's own shape, which hover and selection
// fill. Cells partition the drawing, lie inside the body and are at least 20 x 20 (DeviceArtTests).
//
// Generated by scripts/make-silhouettes.sh from assets/silhouettes/regions.json. Do not edit.

extension DeviceArt {
    static let geometry: [Family: [Part: Geometry]] = ["""


def number(value):
    return ("%.2f" % value).rstrip("0").rstrip(".")


def polygon(points):
    flat = [number(v) for point in points for v in point]
    lines = ["                    " + ", ".join(flat[i:i + 12]) + "," for i in range(0, len(flat), 12)]
    return "Polygon([\n" + "\n".join(lines) + "\n                ])"


def main(source, destination):
    families = json.load(open(source))["families"]
    out = [HEADER]
    for family, case in CASES.items():
        out.append("        .%s: [" % case)
        for part, region in families[family]["regions"].items():
            out.append("            .%s: Geometry(" % part)
            out.append("                hit: " + polygon(region["hit"]) + ",")
            out.append("                outline: " + polygon(region["shape"]) + "),")
        out.append("        ],")
    out.append("    ]\n}")
    open(destination, "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
